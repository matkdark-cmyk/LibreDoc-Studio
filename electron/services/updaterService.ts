import { app, BrowserWindow } from 'electron';
import { autoUpdater, type ProgressInfo, type UpdateInfo } from 'electron-updater';
import fs from 'fs';
import path from 'path';
import type {
  AvailableUpdateInfo,
  GithubRepoStatus,
  SessionStatePatch,
  UpdaterProgressPayload,
  UpdaterState,
} from '../../shared/types';
import { UpdaterWindowController } from '../updaterWindow';
import type { DatabaseService } from './database';

function stripHtmlToPlainText(raw: UpdateInfo['releaseNotes']): string {
  if (!raw) return 'Mejoras de estabilidad, correcciones y compatibilidad de datos garantizada.';
  if (Array.isArray(raw)) {
    return raw
      .map((entry) => {
        const note = typeof entry === 'string' ? entry : entry.note ?? '';
        return stripHtmlToPlainText(note);
      })
      .filter(Boolean)
      .join('\n\n');
  }
  return String(raw)
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/(p|div|li|h[1-6])>/gi, '\n')
    .replace(/<li[^>]*>/gi, '• ')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/&quot;/gi, '"')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function detectGithubRepoConfig(): GithubRepoStatus {
  // 1. Check explicit environment variables if present
  const envOwner = process.env.GH_OWNER?.trim();
  const envRepo = process.env.GH_REPO?.trim();
  if (envOwner && envRepo) {
    return {
      configured: true,
      owner: envOwner,
      repo: envRepo,
      label: `${envOwner}/${envRepo}`,
    };
  }

  // 2. Check package.json repository field
  try {
    const pkgPath = path.join(app.getAppPath(), 'package.json');
    if (fs.existsSync(pkgPath)) {
      const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8')) as {
        repository?: string | { url?: string };
      };
      const repoUrl =
        typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? '';
      const match = repoUrl.match(/github\.com[:/]([^/]+)\/([^/.]+)/i);
      if (match) {
        return {
          configured: true,
          owner: match[1],
          repo: match[2],
          label: `${match[1]}/${match[2]}`,
        };
      }
    }
  } catch {
    // Non-fatal
  }

  // 3. Check packaged app-update.yml (generated by electron-builder) and electron-builder.yml
  const ymlCandidates: string[] = [];
  if (typeof process.resourcesPath === 'string') {
    ymlCandidates.push(path.join(process.resourcesPath, 'app-update.yml'));
  }
  ymlCandidates.push(path.join(process.cwd(), 'electron-builder.yml'));

  for (const ymlPath of ymlCandidates) {
    try {
      if (!fs.existsSync(ymlPath)) continue;
      const content = fs.readFileSync(ymlPath, 'utf8');
      const ownerMatch = content.match(/^\s*owner:\s*["']?([^"'\s#]+)["']?/m);
      const repoMatch = content.match(/^\s*repo:\s*["']?([^"'\s#]+)["']?/m);
      if (
        ownerMatch &&
        repoMatch &&
        ownerMatch[1] !== 'TU_USUARIO_GITHUB' &&
        repoMatch[1] !== 'TU_REPOSITORIO_GITHUB'
      ) {
        return {
          configured: true,
          owner: ownerMatch[1],
          repo: repoMatch[1],
          label: `${ownerMatch[1]}/${repoMatch[1]}`,
        };
      }
    } catch {
      // Non-fatal
    }
  }

  return {
    configured: false,
    owner: null,
    repo: null,
    label: 'GitHub Releases (configurar owner/repo al publicar)',
  };
}

export class UpdaterService {
  private readonly db: DatabaseService;
  private readonly getMainWindow: () => BrowserWindow | null;
  private readonly onBeforeQuitForInstall: () => void;
  private readonly updaterWindow = new UpdaterWindowController();
  private readonly isDevMode: boolean;

  private state: UpdaterState;
  private devSimTimer: NodeJS.Timeout | null = null;
  private installingUpdate = false;

  constructor(params: {
    db: DatabaseService;
    getMainWindow: () => BrowserWindow | null;
    onBeforeQuitForInstall: () => void;
  }) {
    this.db = params.db;
    this.getMainWindow = params.getMainWindow;
    this.onBeforeQuitForInstall = params.onBeforeQuitForInstall;
    this.isDevMode = !app.isPackaged || process.env.NODE_ENV === 'development';

    const meta = this.db.getAppMeta();
    const githubRepo = detectGithubRepoConfig();

    this.state = {
      status: 'idle',
      currentVersion: app.getVersion(),
      autoCheckOnStartup: meta.auto_check_updates === 1,
      lastCheckedAt: meta.last_update_check_at || null,
      githubRepo,
      isDevMode: this.isDevMode,
      availableUpdate: null,
      message: 'Listo para comprobar actualizaciones desde GitHub Releases.',
      error: null,
    };

    this.configureAutoUpdater();
  }

  private configureAutoUpdater(): void {
    // Never download silently before user confirms; explicit silent install on quitAndInstall(true, true)
    autoUpdater.autoDownload = false;
    autoUpdater.autoInstallOnAppQuit = false;
    autoUpdater.allowPrerelease = false;

    autoUpdater.on('checking-for-update', () => {
      this.updateState({
        status: 'checking',
        message: 'Consultando GitHub Releases...',
        error: null,
      });
    });

    autoUpdater.on('update-available', (info: UpdateInfo) => {
      const now = new Date().toISOString();
      this.db.setLastUpdateCheckAt(now);
      const available: AvailableUpdateInfo = {
        version: info.version,
        releaseDate: info.releaseDate,
        releaseNotes: stripHtmlToPlainText(info.releaseNotes),
        isSimulated: false,
      };
      this.updateState({
        status: 'available',
        lastCheckedAt: now,
        availableUpdate: available,
        message: `Nueva versión v${info.version} disponible en GitHub Releases.`,
        error: null,
      });
    });

    autoUpdater.on('update-not-available', () => {
      const now = new Date().toISOString();
      this.db.setLastUpdateCheckAt(now);
      this.updateState({
        status: 'up-to-date',
        lastCheckedAt: now,
        availableUpdate: null,
        message: `Estás usando la última versión disponible (v${this.state.currentVersion}).`,
        error: null,
      });
    });

    autoUpdater.on('download-progress', (progress: ProgressInfo) => {
      const version = this.state.availableUpdate?.version ?? 'nueva';
      const pct = Math.min(99, Math.max(0, Math.round(progress.percent)));
      this.updaterWindow.sendProgress({
        stage: 'downloading',
        version,
        percent: pct,
        bytesPerSecond: Math.round(progress.bytesPerSecond || 0),
        transferredBytes: Math.round(progress.transferred || 0),
        totalBytes: Math.round(progress.total || 0),
        statusMessage: `Descargando actualización v${version}...`,
        theme: this.db.getSessionState().theme,
        isSimulated: false,
      });
    });

    autoUpdater.on('update-downloaded', (info: UpdateInfo) => {
      const version = info.version || this.state.availableUpdate?.version || 'nueva';
      const totalBytes = this.updaterWindow.getLatestPayload()?.totalBytes ?? 0;

      this.updateState({
        status: 'downloaded',
        message: `Actualización v${version} descargada. Preparando instalación...`,
      });

      this.updaterWindow.sendProgress({
        stage: 'verifying',
        version,
        percent: 100,
        bytesPerSecond: 0,
        transferredBytes: totalBytes,
        totalBytes,
        statusMessage: `Verificando instalador de v${version} y preparando reinicio...`,
        theme: this.db.getSessionState().theme,
        isSimulated: false,
      });

      setTimeout(() => {
        this.updaterWindow.sendProgress({
          stage: 'installing',
          version,
          percent: 100,
          bytesPerSecond: 0,
          transferredBytes: totalBytes,
          totalBytes,
          statusMessage: 'Instalando actualización y relanzando LibreDoc Studio...',
          theme: this.db.getSessionState().theme,
          isSimulated: false,
        });

        setTimeout(() => {
          this.installingUpdate = true;
          this.onBeforeQuitForInstall();
          // Silent NSIS install + automatic relaunch where user left off
          autoUpdater.quitAndInstall(true, true);
        }, 650);
      }, 750);
    });

    autoUpdater.on('error', (err: Error) => {
      const msg = err?.message || 'Error desconocido al consultar actualizaciones.';
      this.updateState({
        status: 'error',
        message: 'No se pudo completar la operación de actualización.',
        error: msg,
      });

      if (this.updaterWindow.isOpen()) {
        this.updaterWindow.sendProgress({
          stage: 'error',
          version: this.state.availableUpdate?.version ?? this.state.currentVersion,
          percent: this.updaterWindow.getLatestPayload()?.percent ?? 0,
          bytesPerSecond: 0,
          transferredBytes: this.updaterWindow.getLatestPayload()?.transferredBytes ?? 0,
          totalBytes: this.updaterWindow.getLatestPayload()?.totalBytes ?? 0,
          statusMessage: 'La descarga de la actualización se interrumpió.',
          theme: this.db.getSessionState().theme,
          error: msg,
        });
      }
    });
  }

  private updateState(patch: Partial<UpdaterState>): void {
    this.state = {
      ...this.state,
      ...patch,
    };
    this.broadcastState();
  }

  private broadcastState(): void {
    const win = this.getMainWindow();
    if (win && !win.isDestroyed() && !win.webContents.isDestroyed()) {
      win.webContents.send('updater:state-changed', this.state);
    }
  }

  public isInstallingUpdate(): boolean {
    return this.installingUpdate;
  }

  public getState(): UpdaterState {
    return this.state;
  }

  public getSplashState(): UpdaterProgressPayload | null {
    return this.updaterWindow.getLatestPayload();
  }

  public setAutoCheckUpdates(enabled: boolean): UpdaterState {
    this.db.setAutoCheckUpdates(enabled);
    this.updateState({ autoCheckOnStartup: enabled });
    return this.state;
  }

  public scheduleStartupCheck(): void {
    if (!this.state.autoCheckOnStartup) return;
    if (!app.isPackaged) return;

    setTimeout(() => {
      void this.checkForUpdates();
    }, 2500);
  }

  public async checkForUpdates(): Promise<UpdaterState> {
    if (!app.isPackaged) {
      const now = new Date().toISOString();
      this.db.setLastUpdateCheckAt(now);

      // In dev mode, if a real GitHub owner/repo is configured, query GitHub Releases API live!
      if (this.state.githubRepo.configured && this.state.githubRepo.owner && this.state.githubRepo.repo) {
        this.updateState({
          status: 'checking',
          message: `Consultando GitHub Releases (${this.state.githubRepo.label})...`,
          error: null,
        });
        try {
          const res = await fetch(
            `https://api.github.com/repos/${this.state.githubRepo.owner}/${this.state.githubRepo.repo}/releases/latest`,
            {
              headers: {
                'User-Agent': 'LibreDoc-Studio-Updater',
                Accept: 'application/vnd.github+json',
              },
            },
          );
          if (res.status === 404) {
            this.updateState({
              status: 'up-to-date',
              lastCheckedAt: now,
              availableUpdate: null,
              message: `Repositorio ${this.state.githubRepo.label} conectado; aún no hay releases publicadas.`,
              error: null,
            });
            return this.state;
          }
          if (!res.ok) {
            throw new Error(`GitHub respondió HTTP ${res.status}`);
          }
          const release = (await res.json()) as {
            tag_name?: string;
            published_at?: string;
            body?: string;
          };
          const latestVersion = (release.tag_name ?? '').replace(/^v/i, '');
          if (latestVersion && latestVersion !== this.state.currentVersion) {
            this.updateState({
              status: 'available',
              lastCheckedAt: now,
              availableUpdate: {
                version: latestVersion,
                releaseDate: release.published_at,
                releaseNotes:
                  release.body?.trim() ||
                  'Nueva versión disponible en GitHub Releases.',
                isSimulated: false,
              },
              message: `Nueva versión v${latestVersion} detectada en ${this.state.githubRepo.label}.`,
              error: null,
            });
            return this.state;
          }
          this.updateState({
            status: 'up-to-date',
            lastCheckedAt: now,
            availableUpdate: null,
            message: `Estás en la versión más reciente (v${this.state.currentVersion}).`,
            error: null,
          });
          return this.state;
        } catch (err) {
          this.updateState({
            status: 'error',
            lastCheckedAt: now,
            message: 'No se pudo consultar GitHub Releases desde el modo desarrollo.',
            error: err instanceof Error ? err.message : String(err),
          });
          return this.state;
        }
      }

      this.updateState({
        status: 'up-to-date',
        lastCheckedAt: now,
        availableUpdate: null,
        message:
          'Ejecutando en modo desarrollo sin instalador empaquetado. Usa el modo de prueba local debajo para validar la ventana de descarga y restauración.',
        error: null,
      });
      return this.state;
    }

    try {
      await autoUpdater.checkForUpdates();
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err);
      this.updateState({
        status: 'error',
        message: 'No se pudo comprobar actualizaciones en GitHub Releases.',
        error: msg,
      });
    }

    return this.state;
  }

  public async acceptAndInstallUpdate(
    sessionPatch?: SessionStatePatch,
  ): Promise<{ ok: boolean; error?: string }> {
    const available = this.state.availableUpdate;
    if (!available) {
      return { ok: false, error: 'No hay ninguna actualización pendiente para instalar.' };
    }

    // If this was triggered from the dev-only prompt test, run the dev visual updater window flow
    if (available.isSimulated || !app.isPackaged) {
      return this.startDevUpdateSimulation(sessionPatch, available.version);
    }

    // 1. Persist exact session state synchronously in SQLite with pending_restore = 1
    this.db.prepareUpdateRestore(available.version, sessionPatch);
    const theme = this.db.getSessionState().theme;

    // 2. Hide main window and open dedicated updater progress window
    const mainWin = this.getMainWindow();
    if (mainWin && !mainWin.isDestroyed()) {
      mainWin.hide();
    }

    this.updateState({
      status: 'downloading',
      message: `Descargando actualización v${available.version}...`,
      error: null,
    });

    this.updaterWindow.open({
      stage: 'preparing',
      version: available.version,
      percent: 0,
      bytesPerSecond: 0,
      transferredBytes: 0,
      totalBytes: 0,
      statusMessage: `Conectando con GitHub Releases para v${available.version}...`,
      theme,
      isSimulated: false,
    });

    // 3. Begin real download via electron-updater
    try {
      await autoUpdater.downloadUpdate();
      return { ok: true };
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err);
      this.updaterWindow.sendProgress({
        stage: 'error',
        version: available.version,
        percent: 0,
        bytesPerSecond: 0,
        transferredBytes: 0,
        totalBytes: 0,
        statusMessage: 'Error iniciando la descarga desde GitHub Releases.',
        theme,
        error: msg,
      });
      return { ok: false, error: msg };
    }
  }

  /**
   * DEV-ONLY: Opens the exact "Nueva versión disponible" prompt so the user can test
   * accepting/deferring updates before building on GitHub Actions.
   */
  public triggerDevUpdatePrompt(): UpdaterState {
    if (!this.isDevMode) {
      return this.state;
    }

    const simulatedVersion = '0.2.0-test';
    this.updateState({
      status: 'available',
      availableUpdate: {
        version: simulatedVersion,
        releaseDate: new Date().toISOString(),
        releaseNotes:
          'Prueba visual en entorno de desarrollo (no instala archivos reales):\n• Guarda tu sesión actual en SQLite (pending_restore = 1).\n• Oculta la ventana principal y abre la ventana dedicada de descarga (0% a 100%).\n• Restaura tu documento, página, zoom y campos exactamente donde quedaste.',
        isSimulated: true,
      },
      message: `Aviso de prueba listo (v${simulatedVersion}).`,
      error: null,
    });

    return this.state;
  }

  /**
   * DEV-ONLY: Exercises the real SQLite session_state persistence + dedicated updaterWindow
   * with live 0%..100% progress, MB/s speed, and exact session restoration on main window reload.
   */
  public startDevUpdateSimulation(
    sessionPatch?: SessionStatePatch,
    versionLabel = '0.2.0-test',
  ): { ok: boolean; error?: string } {
    if (!this.isDevMode) {
      return {
        ok: false,
        error: 'El modo de prueba visual solo está habilitado en entorno de desarrollo.',
      };
    }

    if (this.devSimTimer) {
      clearInterval(this.devSimTimer);
      this.devSimTimer = null;
    }

    // 1. Real SQLite flush with pending_restore = 1 & banner flag
    this.db.prepareUpdateRestore(versionLabel, sessionPatch);
    const theme = this.db.getSessionState().theme;

    // 2. Hide main window & launch real dedicated updaterWindow
    const mainWin = this.getMainWindow();
    if (mainWin && !mainWin.isDestroyed()) {
      mainWin.hide();
    }

    const totalBytes = 68 * 1024 * 1024; // 68 MB installer size
    let transferred = 0;

    this.updaterWindow.open({
      stage: 'preparing',
      version: versionLabel,
      percent: 0,
      bytesPerSecond: 0,
      transferredBytes: 0,
      totalBytes,
      statusMessage: `Preparando descarga de v${versionLabel} (prueba local)...`,
      theme,
      isSimulated: true,
    });

    this.devSimTimer = setInterval(() => {
      const speedBytes = Math.round((7.2 + Math.random() * 4.8) * 1024 * 1024);
      const stepBytes = Math.round(speedBytes * 0.22);
      transferred = Math.min(totalBytes, transferred + stepBytes);
      const percent = Math.min(100, Math.round((transferred / totalBytes) * 100));

      if (percent < 100) {
        this.updaterWindow.sendProgress({
          stage: 'downloading',
          version: versionLabel,
          percent,
          bytesPerSecond: speedBytes,
          transferredBytes: transferred,
          totalBytes,
          statusMessage: `Descargando actualización v${versionLabel}...`,
          theme,
          isSimulated: true,
        });
        return;
      }

      if (this.devSimTimer) {
        clearInterval(this.devSimTimer);
        this.devSimTimer = null;
      }

      this.updaterWindow.sendProgress({
        stage: 'verifying',
        version: versionLabel,
        percent: 100,
        bytesPerSecond: 0,
        transferredBytes: totalBytes,
        totalBytes,
        statusMessage: 'Verificando instalador NSIS y preparando reinicio...',
        theme,
        isSimulated: true,
      });

      setTimeout(() => {
        this.updaterWindow.sendProgress({
          stage: 'installing',
          version: versionLabel,
          percent: 100,
          bytesPerSecond: 0,
          transferredBytes: totalBytes,
          totalBytes,
          statusMessage: 'Reiniciando y restaurando tu sesión guardada...',
          theme,
          isSimulated: true,
        });

        setTimeout(() => {
          this.updaterWindow.close();
          this.updateState({
            status: 'up-to-date',
            availableUpdate: null,
            message: `Prueba de actualización v${versionLabel} completada con restauración de sesión.`,
          });

          const targetMain = this.getMainWindow();
          if (targetMain && !targetMain.isDestroyed()) {
            // Reload main window cleanly so bootstrap runs full SQLite restore + confirmation banner
            targetMain.webContents.reload();
            targetMain.once('ready-to-show', () => {
              targetMain.show();
              targetMain.focus();
            });
            // Fallback show if already ready
            setTimeout(() => {
              if (!targetMain.isDestroyed() && !targetMain.isVisible()) {
                targetMain.show();
                targetMain.focus();
              }
            }, 350);
          }
        }, 700);
      }, 750);
    }, 180);

    return { ok: true };
  }

  public cancelAndReturnToMain(): void {
    if (this.devSimTimer) {
      clearInterval(this.devSimTimer);
      this.devSimTimer = null;
    }
    this.updaterWindow.close();
    const mainWin = this.getMainWindow();
    if (mainWin && !mainWin.isDestroyed()) {
      mainWin.show();
      mainWin.focus();
    }
  }

  public dispose(): void {
    if (this.devSimTimer) {
      clearInterval(this.devSimTimer);
      this.devSimTimer = null;
    }
    this.updaterWindow.close();
  }
}
